"""Doc comments that describe a definition: the text a developer wrote for it."""

import ast
import re

COMMENT_START = ("//", "/*", "*", "#", "--", "'''", '"""')
COMMENT_MARKER = re.compile(r"^\s*(///?|/\*+!?|\*+/?|#+|--)\s?")
BOILERPLATE = re.compile(r"copyright|spdx-license|licensed under|generated by|do not edit|@generated",
                         re.IGNORECASE)
ANNOTATION = re.compile(r"^\s*(@|#\[)")  # Java/Python/TS decorators, Rust attributes


def _is_comment(line):
    text = line.strip()
    return text.startswith(COMMENT_START) and not text.startswith(("#include", "#define", "#!", "#pragma"))


def _clean(parts):
    text = " ".join(p for p in parts if p)
    return re.sub(r"\s+", " ", text).strip()


def leading_comment(lines, line):
    """The comment block directly above 1-based `line`, skipping annotations.

    Returns "" for license headers, generated-file markers and preprocessor
    lines, which describe a file rather than the definition."""
    i = line - 2
    while i >= 0 and ANNOTATION.match(lines[i]):
        i -= 1

    collected = []
    while i >= 0 and _is_comment(lines[i]):
        collected.insert(0, COMMENT_MARKER.sub("", lines[i].strip()).rstrip("*/ ").strip())
        i -= 1

    text = _clean(collected)
    return "" if BOILERPLATE.search(text) else text


def python_docstrings(source):
    """{1-based def/class line: (docstring, 0-based lines it occupies)}.

    Python documents a function inside its body, so callers must remove these
    lines from the positive text or the query would appear in its own answer."""
    try:
        tree = ast.parse(source)
    except (SyntaxError, ValueError):
        return {}

    found = {}
    for node in ast.walk(tree):
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            continue
        if not node.body or not isinstance(node.body[0], ast.Expr):
            continue

        value = node.body[0].value
        if isinstance(value, ast.Constant) and isinstance(value.value, str):
            expr = node.body[0]
            line = node.decorator_list[0].lineno if node.decorator_list else node.lineno
            found[line] = (_clean(value.value.split("\n")), set(range(expr.lineno - 1, expr.end_lineno)))
    return found
